// Real browser, release build, live Testnet: full Practice Lab cycle through the real revoke dialog.
import { chromium } from 'playwright'; import { readFileSync } from 'fs'; import http from 'http';
const FILE = process.argv[2], SHOTS = process.argv[3];
let fails = 0; const check = (c, m) => { console.log(`${c ? 'PASS' : 'FAIL'} ${m}`); if (!c) fails++; };
const html = readFileSync(FILE); const srv = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); r.end(html); }).listen(8767);
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1100, height: 1000 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('http://localhost:8767/');
check(!(await p.isVisible('#lab')), 'lab hidden on Mainnet');
await p.click('.net [data-net="testnet"]');
check(await p.isVisible('#lab'), 'lab visible on Testnet');
const logHas = (re, ms = 90000) => p.waitForFunction((src) => new RegExp(src).test(document.querySelector('#lab-log').innerText), re.source, { timeout: ms }).then(() => true).catch(() => false);
await p.click('#lab-create');
check(await logHas(/Practice owner/), 'step 1: accounts created');
check(/Practice Lab \(Testnet\)/.test(await p.innerText('#wallet-status')), 'practice wallet connected');
if (SHOTS) await p.screenshot({ path: `${SHOTS}/lab-1-created.png`, fullPage: true });
await p.click('#lab-grant');
check(await logHas(/now holds Payment/), 'step 2: grant confirmed');
await p.waitForSelector('.card-revoke', { timeout: 60000 }).catch(() => {});
check(/Critical/.test(await p.innerText('#results')), 'scan shows Critical delegate');
if (SHOTS) { await p.screenshot({ path: `${SHOTS}/lab-2-granted.png`, fullPage: true }); await p.locator('#results').screenshot({ path: `${SHOTS}/lab-2-results.png` }); }
await p.click('#lab-spend');
check(await logHas(/moved 1 XRP/), 'step 3: helper moved 1 XRP');
await p.waitForTimeout(4000);
const resText = await p.innerText('#results');
check(/already|used|sent/i.test(resText), 'scan reports delegate activity');
if (SHOTS) await p.screenshot({ path: `${SHOTS}/lab-3-spent.png`, fullPage: true });
await p.waitForSelector('.card-revoke', { timeout: 60000 });
await p.click('.card-revoke');
await p.waitForSelector('#revoke-go:not([hidden])', { timeout: 30000 });
check((await p.innerText('#revoke-go')) === 'Sign with the practice key', 'dialog labels the practice signer');
const dlg = await p.innerText('#revoke-body');
check(/Strict check passed/.test(dlg) && /Wallet is on testnet/.test(dlg), 'strict check + network lock passed in dialog');
if (SHOTS) await p.locator('#revoke-dialog').screenshot({ path: `${SHOTS}/lab-4-dialog.png` });
await p.click('#revoke-go');
const ok = await p.waitForFunction(() => /Revoked/.test(document.querySelector('#revoke-body').innerText), null, { timeout: 120000 }).then(() => true).catch(() => false);
const after = await p.innerText('#revoke-body');
check(ok, 'step 4: revoke confirmed: ' + after.replace(/\s+/g, ' ').slice(0, 160));
if (SHOTS) await p.locator('#revoke-dialog').screenshot({ path: `${SHOTS}/lab-5-revoked.png` });
await p.click('#revoke-close');
await p.click('#lab-prove');
check(await logHas(/terNO_DELEGATE_PERMISSION/), 'step 5: ledger refused the helper');
await p.waitForTimeout(3000);
if (SHOTS) { await p.screenshot({ path: `${SHOTS}/lab-6-proved.png`, fullPage: true }); await p.locator('#lab').screenshot({ path: `${SHOTS}/lab-6-panel.png` }); await p.locator('#results').screenshot({ path: `${SHOTS}/lab-6-results.png` }); }
await p.click('.net [data-net="mainnet"]');
check(/Practice Lab closed/.test(await p.innerText('#wallet-status')) && (await p.innerText('#lab-log')) === '', 'leaving Testnet forgets the lab');
check(errs.length === 0, 'no page errors' + (errs.length ? ': ' + errs.join(' | ') : ''));
await b.close(); srv.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED'); process.exit(fails ? 1 : 0);
